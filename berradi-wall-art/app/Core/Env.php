<?php

declare(strict_types=1);

namespace App\Core;

/**
 * Minimal .env loader (no external dependency, works on any shared host).
 */
final class Env
{
    /** @var array<string,string> */
    private static array $values = [];

    public static function load(string $file): void
    {
        if (!is_file($file) || !is_readable($file)) {
            return;
        }
        $lines = file($file, FILE_IGNORE_NEW_LINES | FILE_SKIP_EMPTY_LINES) ?: [];
        foreach ($lines as $line) {
            $line = trim($line);
            if ($line === '' || str_starts_with($line, '#') || !str_contains($line, '=')) {
                continue;
            }
            [$key, $value] = explode('=', $line, 2);
            $key = trim($key);
            if (!preg_match('/^[A-Z0-9_]+$/i', $key)) {
                continue;
            }
            self::$values[$key] = self::parseValue(trim($value));
        }
    }

    private static function parseValue(string $value): string
    {
        if ($value === '') {
            return '';
        }
        $first = $value[0];
        if (($first === '"' || $first === "'") && str_ends_with($value, $first) && strlen($value) >= 2) {
            $inner = substr($value, 1, -1);
            if ($first === '"') {
                $inner = str_replace(['\\n', '\\"', '\\\\'], ["\n", '"', '\\'], $inner);
            }
            return $inner;
        }
        // strip inline comments for unquoted values
        $hash = strpos($value, ' #');
        if ($hash !== false) {
            $value = rtrim(substr($value, 0, $hash));
        }
        return $value;
    }

    public static function get(string $key, mixed $default = null): mixed
    {
        if (array_key_exists($key, self::$values)) {
            $value = self::$values[$key];
        } else {
            $env = getenv($key);
            if ($env === false) {
                return $default;
            }
            $value = $env;
        }
        return match (strtolower($value)) {
            'true', '(true)' => true,
            'false', '(false)' => false,
            'null', '(null)' => null,
            default => $value,
        };
    }

    public static function set(string $key, string $value): void
    {
        self::$values[$key] = $value;
    }

    public static function reset(): void
    {
        self::$values = [];
    }

    /**
     * Build the content of an .env file from key/value pairs (used by the installer).
     *
     * @param array<string,string|int|bool|null> $pairs
     */
    public static function build(array $pairs): string
    {
        $out = "# Generated by BERRADI WALL ART installer on " . date('Y-m-d H:i:s') . "\n";
        foreach ($pairs as $key => $value) {
            if (is_bool($value)) {
                $value = $value ? 'true' : 'false';
            }
            $value = (string) $value;
            if ($value === '' || preg_match('/^[A-Za-z0-9_.:\/@+-]+$/', $value)) {
                $out .= "{$key}={$value}\n";
            } else {
                $escaped = str_replace(['\\', '"', "\n"], ['\\\\', '\\"', '\\n'], $value);
                $out .= "{$key}=\"{$escaped}\"\n";
            }
        }
        return $out;
    }
}
